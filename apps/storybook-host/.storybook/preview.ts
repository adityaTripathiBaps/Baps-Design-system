// ── Keep implementation internals out of the Controls panel ────────────────
//
// Compodoc documents every PUBLIC class member, and Storybook turns each one
// into a Controls row. For a ControlValueAccessor that means `writeValue`,
// `registerOnChange`, `registerOnTouched`, `setDisabledState` and the internal
// `value` field all appear as controls — as do computed getters like `dt`,
// `resolvedPanelStyleClass` and `panelClass`, and imperative methods like
// `toggle`, `open`, `close`, `apply`.
//
// Measured: 137 distinct non-input members across the library. On
// `baps-slider` that was 17 placeholder rows against 7 real controls, so the
// panel read as a list of "Set object" buttons rather than something a reader
// could drive.
//
// Derived here rather than hand-listed, for two reasons: 137 names is not
// maintainable by hand, and the list has to stay correct as components change.
// docJson is regenerated by compodoc on every Storybook start, so this is
// always in step with the source.
//
// The subtraction matters. A name is only excluded if it is an @Input or
// @Output on NO component — `value` is a real input on some components and a
// CVA field on others, and excluding it globally would hide a control people
// need.
const declaredIO = new Set<string>();
const otherMembers = new Set<string>();

for (const component of (docJson as { components?: unknown[] }).components ?? []) {
  const c = component as {
    inputsClass?: { name: string }[];
    outputsClass?: { name: string }[];
    propertiesClass?: { name: string }[];
    methodsClass?: { name: string }[];
    accessors?: Record<string, unknown>;
  };
  for (const i of c.inputsClass ?? []) declaredIO.add(i.name);
  for (const o of c.outputsClass ?? []) declaredIO.add(o.name);
  for (const p of c.propertiesClass ?? []) otherMembers.add(p.name);
  for (const m of c.methodsClass ?? []) otherMembers.add(m.name);
  for (const a of Object.keys(c.accessors ?? {})) otherMembers.add(a);
}

const CONTROLS_EXCLUDE = [...otherMembers].filter((name) => !declaredIO.has(name));

