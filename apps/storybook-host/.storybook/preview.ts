// PrimeNG hardcodes `.p-button { font-size: 1rem }` in its base stylesheet —
// .p-button-sm/.p-button-lg DO consume definePreset tokens, but the unsized
// default does not, so it can't be fixed via baps.theme.ts alone. Figma node
// 22465:93605 specifies 14px for the default (M) size. Injected directly
// (rather than via a .css import) since cross-package CSS imports from
// .storybook/preview.ts were not reliably reaching the bundle here.
if (typeof document !== 'undefined') {
  const style = document.createElement('style');
  style.textContent = `
    .p-button:not(.p-button-sm):not(.p-button-lg) { font-size: 14px; }
  `;
  document.head.appendChild(style);

  // The docs-shell chrome (dark-mode surfaces, prose, code blocks, arg
  // tables, page rhythm, syntax colours) used to be injected here as two
  // more <style> blocks. It now lives in ../src/_docs-shell.scss, imported
  // through ../src/styles.scss above, so the values come from a token tier
  // instead of literals and the rules no longer name the mode.


  // storybook-dark-mode only toggles its class on the MANAGER body — the preview
  // iframe never receives it, so PrimeNG's darkModeSelector ('.baps-dark') and the
  // docs dark rules above never activate and the inner content stays light while
  // the chrome flips. Bridge the addon's channel event into the iframe: mirror
  // .baps-dark / .baps-light onto the iframe body so the whole preview + docs page
  // switches with the toolbar toggle. Initial state comes from the addon's own
  // persisted store (STORAGE_KEY 'sb-addon-themes-3') so a freshly-loaded docs
  // iframe isn't stuck light until the first event arrives.
  const setDark = (isDark: boolean) => {
    document.body.classList.toggle('baps-dark', isDark);
    document.body.classList.toggle('baps-light', !isDark);
  };
  let initialDark = false;
  try {
    initialDark = JSON.parse(localStorage.getItem('sb-addon-themes-3') ?? '{}').current === 'dark';
  } catch {
    /* no persisted mode yet — default to light */
  }
  setDark(initialDark);
  addons.getChannel().on(DARK_MODE_EVENT_NAME, setDark);

  // Hide PrimeNG overlay masks (drawer, dialog, …) on the merged Docs page
  // only — matching PrimeNG's own reference docs (primeng.dev), where
  // opening a demo's drawer never dims the surrounding page at all. PrimeNG
  // always appends its mask (`position: fixed`, class `p-drawer-mask`/
  // `p-dialog-mask`/…) to `document.body` regardless of any `appendTo`
  // input — see baps-drawer's own doc comment — and it is never a DOM
  // descendant of `.docs-story`, so no CSS containment rule can reach it.
  // Transparent rather than removed/reparented: PrimeNG's own close logic
  // still finds it exactly where it left it (`document.body.removeChild`,
  // which throws if the node moved parents in the meantime) and the click
  // catcher backing "dismiss on backdrop click" still works.
  //
  // A standalone story canvas (Playground, Open, …) has no `.docs-story` on
  // the page at all, so `document.querySelector` below returns null and the
  // mask is left alone — a real dim there is correct, matching production.
  new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      for (const node of mutation.addedNodes) {
        if (!(node instanceof HTMLElement) || !node.className.includes('-mask')) continue;
        if (!document.querySelector('.docs-story')) continue;
        node.style.background = 'transparent';
      }
    }
  }).observe(document.body, { childList: true });
}

// Applies the design system chosen in the toolbar ("Design system" dropdown):
// - provides the selected preset to providePrimeNG so every (re)bootstrap —
//   Storybook re-bootstraps the Angular app on story navigation — starts on
//   the right theme, with no flash of the wrong preset
// - calls usePreset() for live toolbar switches, since PrimeNG's theme is a
//   document-level singleton and a running app won't re-read its providers
// - toggles the .baps-ds-sampark body class, which scopes the extra CSS that
//   PrimeNG tokens can't express (e.g. Sampark button heights)
// Named MyBky, not Baps: the preset is the MyBKY skin and always was. The old
// `Baps` name survives as a deprecated alias for the two consuming apps.
const DS_PRESETS = { mybky: MyBky, sampark: Sampark };
let activePreset: string | undefined;

// ── One ramp, two sinks ─────────────────────────────────────────────────────
//
// Picking a primary swatch used to re-theme HALF the preview. `usePreset()`
// moves everything painted from PrimeNG's `--p-*`, and the design system paints
// a great deal from its OWN tokens — 23 of them reference a MyBKY blue step.
// Measured before this existed: at `accent:rose`, `--p-primary-color` went to
// #cf3650 while `--color-mybky-blue-600` stayed #5f78b8, and a primary tag
// rendered entirely blue (bg #eef0f8, border #9fadd9@20%, text #384871) against
// rose buttons.
//
// So the same ramp now feeds both: `withAccent` hands it to PrimeNG, and this
// writes it onto the design system's own custom properties. `PRIMARY_RAMPS` is
// read rather than re-derived, because the four BAPS accents are hand-authored
// token ramps and `palette(swatch.color)` would produce different values for
// them — two ramps, and the drift would be invisible.
//
// The derived tokens follow for free: `--color-mybky-blue-alpha10` is
// `rgb(from var(--color-mybky-blue-600) r g b / 0.1)`, so it re-tints itself.

// ── Scaffolded brands ───────────────────────────────────────────────────────
//
// BAPS default and App Sell are in the switcher but have no palette. They are
// listed rather than hidden so the intended set is visible and adding a palette
// is a data change, not a feature.
//
// Selecting one does NOT skin the preview. Guessing — falling back to MyBKY
// silently, or dropping to raw Material — produces a page that looks like a
// brand and is not one, and someone eventually screenshots it as if it were.
// The preview stays on the MyBKY base and says why, which is honest and
// reversible the moment the colours arrive.
const AWAITING_PALETTE: Record<string, string> = {
  baps: 'BAPS default',
  appsell: 'App Sell',
};

const NOTICE_ID = 'baps-awaiting-palette';
const NOTICE_STYLE_ID = 'baps-awaiting-palette-style';

